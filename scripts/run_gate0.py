"""Run Gate G0 end to end: download, match, report.

Usage:
    python scripts/run_gate0.py [--force-refresh]

Writes:
    data/raw/                      cached downloads (gitignored)
    data/interim/segments.csv      named highway segments with state
    data/interim/label_matches.csv every maintenance event with its best match
    docs/label-matching-report.md  the gate verdict
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from roadsense import config, gate0, grid3, ocds  # noqa: E402
from roadsense.io import download, extract_tarball, fetch_json, write_manifest  # noqa: E402
from roadsense.states import normalise_state_name  # noqa: E402

CACHE_SEGMENTS = config.DATA_INTERIM / "segments.csv"
CACHE_EVENTS = config.DATA_INTERIM / "events.csv"
CACHE_MATCHES = config.DATA_INTERIM / "label_matches.csv"
REPORT = config.DOCS / "label-matching-report.md"


def get_ocds(force: bool) -> pd.DataFrame:
    """Fetch and cache the OCDS bundle, then extract maintenance events."""
    if CACHE_EVENTS.exists() and not force:
        return pd.read_csv(CACHE_EVENTS)

    archive = download(config.OCDS_CSV_URL, config.DATA_RAW / "ng_ocds_full.csv.tar.gz", force=force)
    bundle = extract_tarball(archive, config.DATA_RAW / "ocds", force=force)
    raw = ocds.load_main(bundle)

    stats = ocds.summarise_filter(raw)
    events = ocds.extract_events(raw)
    events["_filter_stats"] = ""  # placeholder column keeps the CSV header stable

    CACHE_EVENTS.parent.mkdir(parents=True, exist_ok=True)
    events.drop(columns=["_filter_stats"]).to_csv(CACHE_EVENTS, index=False)

    manifest = config.DATA_RAW / "manifest.json"
    write_manifest(manifest, {"ocds": config.OCDS_CSV_URL, "grid3": config.GRID3_ROADS_URL})
    print(f"[ocds] processes={stats['total_processes']:,} events={len(events):,}")
    for key, value in stats.items():
        print(f"  {key:32s} {value:>8,}")
    return events


def get_segments(force: bool) -> pd.DataFrame:
    """Fetch and cache named highway segments with their state assignment."""
    if CACHE_SEGMENTS.exists() and not force:
        return pd.read_csv(CACHE_SEGMENTS)

    print("[grid3] fetching named highway segments ...")
    segments = grid3.fetch_segments()
    print(f"[grid3] {len(segments):,} segments")

    print("[adm1] fetching state boundaries ...")
    meta = fetch_json(config.ADM1_API_URL)
    geojson_path = download(meta["gjDownloadURL"], config.DATA_RAW / "nga_adm1.geojson")
    polygons = grid3.load_boundaries(geojson_path)
    print(f"[adm1] {len(polygons)} polygons")

    segments = grid3.assign_states(segments, polygons)
    segments["state"] = segments["state"].map(normalise_state_name)

    CACHE_SEGMENTS.parent.mkdir(parents=True, exist_ok=True)
    segments.to_csv(CACHE_SEGMENTS, index=False)
    missing = int(segments["state"].isna().sum())
    print(f"[grid3] state assigned for {len(segments) - missing:,}, missing {missing:,}")
    return segments


def write_report(events: pd.DataFrame, segments: pd.DataFrame, matches: pd.DataFrame) -> dict:
    """Render the markdown gate report and return the summary."""
    summary = gate0.summarise(matches)
    reasons = gate0.diagnose_unmatched(matches, segments)
    outcome = gate0.verdict(summary)
    corridors = int(segments["names"].nunique())

    bands = ["high", "medium", "low", "none"]
    by_state = (
        matches.groupby(["state", "confidence"])
        .size()
        .unstack(fill_value=0)
        .reindex(columns=bands, fill_value=0)
        .sort_values("high", ascending=False)
    )
    by_year = (
        matches.groupby(["year", "confidence"])
        .size()
        .unstack(fill_value=0)
        .reindex(columns=bands, fill_value=0)
        .sort_index()
    )

    lines: list[str] = [
        "# Gate G0 — label matching report",
        "",
        "Generated by `scripts/run_gate0.py`. Do not edit by hand.",
        "",
        f"## Verdict: **{outcome}**",
        "",
        f"- High-confidence matched events: **{summary['high']:,}**",
        f"- Thresholds: proceed at ≥{config.GATE_PROCEED}, "
        f"conditional at ≥{config.GATE_CONDITIONAL}, stop below that",
        "",
        "## Counts",
        "",
        "| Stage | Count |",
        "|---|---:|",
        f"| Named highway segments | {len(segments):,} |",
        f"| Segments with a state | {int(segments['state'].notna().sum()):,} |",
        f"| Maintenance events extracted | {summary['events']:,} |",
        f"| Events with both state and road phrase | {summary['events_with_state_and_phrase']:,} |",
        f"| Matched — high | {summary['high']:,} |",
        f"| Matched — medium | {summary['medium']:,} |",
        f"| Matched — low | {summary['low']:,} |",
        f"| Unmatched | {summary['none']:,} |",
        f"| Unique segments at high confidence | {summary['unique_segments_high']:,} |",
        f"| Unique road names at high confidence | {summary['unique_road_names_high']:,} |",
        f"| Distinct corridor names in GRID3 (named segments) | {corridors:,} |",
        f"| Median score (high) | {summary['median_score_high']:.3f} |",
        "",
        "## Why the unmatched events failed",
        "",
        "| Reason | Events | Meaning |",
        "|---|---:|---|",
        f"| Road absent from GRID3 names | {reasons['road_absent_from_grid3']:,} | "
        "No token in the phrase appears in any named road in the country |",
        f"| Only one token shared | {reasons['single_token_only']:,} | "
        "One shared token cannot establish identity |",
        f"| Below confidence | {reasons['below_confidence']:,} | "
        "Tokens line up but not strongly enough to accept |",
        "",
        f"The decisive constraint: GRID3 gives names to **{corridors:,} distinct corridors** "
        f"covering {len(segments):,} segments. The other 113,004 highway segments carry an empty "
        "name, so name-based joining can never reach them.",
        "",
        "## Match rate by state",
        "",
        _to_markdown(by_state, index_label="State"),
        "",
        "## Match rate by year",
        "",
        _to_markdown(by_year, index_label="Year"),
        "",
        "## Sample high-confidence matches",
        "",
        "| Procurement phrase | GRID3 segment name | Score |",
        "|---|---|---:|",
    ]

    high = matches[matches["confidence"] == "high"].sort_values("score", ascending=False)
    for row in high.head(25).itertuples(index=False):
        lines.append(
            f"| {_clip(row.road_phrase, 55)} | {_clip(row.matched_name, 45)} | {row.score:.2f} |"
        )
    if high.empty:
        lines.append("| _(none)_ | | |")

    lines += [
        "",
        "## Sample low-confidence matches (must not enter training)",
        "",
        "| Procurement phrase | Best guess | Score |",
        "|---|---|---:|",
    ]
    low = matches[matches["confidence"] == "low"].sort_values("score", ascending=False)
    for row in low.head(15).itertuples(index=False):
        lines.append(
            f"| {_clip(row.road_phrase, 55)} | {_clip(row.matched_name, 45)} | {row.score:.2f} |"
        )
    if low.empty:
        lines.append("| _(none)_ | | |")

    lines += [
        "",
        "## Method",
        "",
        "1. Filter OCDS to FERMA / Ministry of Works buyers whose text mentions a carriageway.",
        "2. Classify the intervention; keep maintenance and rehabilitation, drop new construction,",
        "   access roads and street-lighting noise.",
        "3. Extract the road phrase and the named state.",
        "4. Match against GRID3 `names` restricted to the same state; tokens are compared with a",
        "   fuzzy ratio so spelling drift (Karlhi/Karlahi) still joins.",
        "5. Band by confidence. Only **high** enters training; medium goes to a review queue.",
        "",
        "## Caveats",
        "",
        "- A procurement record is evidence of **spending**, not of a road physically failing.",
        "- Only 32.3% of highway segments carry a name, so the matched universe is a subset of the",
        "  network. Coverage is reported, not papered over.",
        "- The 2022 gap in the source means no model can be trained across that year.",
        "",
    ]

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    return summary


def _to_markdown(frame: pd.DataFrame, index_label: str) -> str:
    """Render a small DataFrame as a markdown table without extra dependencies."""
    if frame.empty:
        return "_(no rows)_"
    columns = list(frame.columns)
    header = "| " + index_label + " | " + " | ".join(str(c) for c in columns) + " |"
    divider = "|---|" + "---:|" * len(columns)
    rows = [
        "| " + str(index) + " | " + " | ".join(str(int(v)) for v in values) + " |"
        for index, values in zip(frame.index, frame.to_numpy(), strict=True)
    ]
    return "\n".join([header, divider, *rows])


def _clip(value: object, width: int) -> str:
    text = str(value) if value is not None else ""
    return text if len(text) <= width else text[: width - 1] + "…"


def main() -> int:
    parser = argparse.ArgumentParser(description="Run Gate G0 label matching")
    parser.add_argument("--force-refresh", action="store_true", help="ignore cached downloads")
    args = parser.parse_args()

    events = get_ocds(args.force_refresh)
    segments = get_segments(args.force_refresh)

    events = events[events["state"].notna() & events["road_phrase"].notna()].copy()
    print(f"[gate0] matching {len(events):,} events against {len(segments):,} segments ...")
    matches = gate0.match_events(events, segments)

    CACHE_MATCHES.parent.mkdir(parents=True, exist_ok=True)
    matches.to_csv(CACHE_MATCHES, index=False)

    summary = write_report(events, segments, matches)
    print("\n[gate0] summary")
    for key, value in summary.items():
        print(f"  {key:32s} {value}")
    print(f"\n[gate0] VERDICT: {gate0.verdict(summary)}")
    print(f"[gate0] report: {REPORT.relative_to(config.ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
